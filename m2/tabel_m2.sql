-- 3. Tabel Transaksi / Pesanan
CREATE TABLE IF NOT EXISTS public.transaksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total_harga INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabel Detail Transaksi
CREATE TABLE IF NOT EXISTS public.detail_transaksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_id BIGINT REFERENCES public.transaksi(id) ON DELETE CASCADE,
    produk_id BIGINT REFERENCES public.produk(id),
    jumlah INT NOT NULL,
    subtotal INT NOT NULL
);


