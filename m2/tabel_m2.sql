-- 1. Buat Tabel Produk
CREATE TABLE IF NOT EXISTS public.produk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(255) NOT NULL,
    harga INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

