-- 1. Tabel Pelanggan
CREATE TABLE IF NOT EXISTS public.pelanggan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    kategori VARCHAR(50) DEFAULT 'Member',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

